#!/usr/bin/env node

/**
 * Build the type/weakness profiles for the exact Gen IV source cards used by
 * National Dex 001-151 in src/core/constants/gen4-card-art.ts.
 *
 * TCG type and weakness are properties of an individual printed card, not a
 * direct copy of the video-game type chart. TCGdex exposes those fields on its
 * single-card endpoint, so the renderer can match the illustration it chose.
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const ART_FILE = path.resolve('src/core/constants/gen4-card-art.ts');
const OUT = path.resolve('src/core/constants/gen4-tcg-profiles.generated.ts');
const API = 'https://api.tcgdex.net/v2/en/cards';

async function fetchJson(url) {
  let lastError;
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const response = await fetch(url, { headers: { 'user-agent': 'pokedex-data-builder/1.0' } });
      if (!response.ok) throw new Error(`${response.status} ${response.statusText}`);
      return response.json();
    } catch (error) {
      lastError = error;
      await new Promise(resolve => setTimeout(resolve, attempt * 250));
    }
  }
  throw new Error(`${lastError?.message ?? lastError}: ${url}`);
}

async function mapLimit(values, limit, fn) {
  const results = new Array(values.length);
  let next = 0;
  await Promise.all(Array.from({ length: Math.min(limit, values.length) }, async () => {
    while (next < values.length) {
      const index = next++;
      results[index] = await fn(values[index], index);
    }
  }));
  return results;
}

function sourceCards(source) {
  const cards = new Map();
  let era = null;
  for (const line of source.split('\n')) {
    const declaration = line.match(/^export const GEN4_CARD_ART_(DP|PL|HGSS):/);
    if (declaration) era = declaration[1].toLowerCase();
    if (era && line.trim() === '};') era = null;
    if (!era) continue;
    const match = line.match(/^\s+(\d+): '([^']+)',/);
    if (!match || Number(match[1]) > 151) continue;
    const cardPath = match[2];
    const parts = cardPath.match(/^\/cards\/gen4\/([^/]+)\/([^/.]+)\.jpg$/);
    if (!parts) throw new Error(`Unrecognized Gen IV card path: ${cardPath}`);
    cards.set(`${era}:${match[1]}`, {
      era,
      species: Number(match[1]),
      cardPath,
      cardId: `${parts[1]}-${parts[2]}`,
    });
  }
  return [...cards.values()];
}

async function main() {
  const selectedCards = sourceCards(await readFile(ART_FILE, 'utf8'));
  const unique = [...new Map(selectedCards.map(card => [card.cardId, card])).values()];
  const details = await mapLimit(unique, 8, async (card, index) => {
    if ((index + 1) % 100 === 0) console.log(`  ${index + 1}/${unique.length}`);
    const data = await fetchJson(`${API}/${encodeURIComponent(card.cardId)}`);
    if (!data.types?.length) throw new Error(`No TCG type for ${card.cardId}`);
    return {
      ...card,
      name: data.name,
      type: data.types[0],
      weaknesses: (data.weaknesses ?? []).map(weakness => ({
        type: weakness.type,
        ...(weakness.value ? { value: weakness.value } : {}),
      })),
      stage: data.stage ?? null,
      evolvesFrom: data.evolveFrom ?? null,
      sourceUrl: `${API}/${encodeURIComponent(card.cardId)}`,
    };
  });

  const byId = new Map(details.map(detail => [detail.cardId, detail]));
  const profiles = Object.fromEntries(selectedCards.map(card => {
    const detail = byId.get(card.cardId);
    return [card.cardPath, {
      cardId: card.cardId,
      name: detail.name,
      era: card.era,
      type: detail.type,
      weaknesses: detail.weaknesses,
      stage: detail.stage,
      evolvesFrom: detail.evolvesFrom,
      sourceUrl: detail.sourceUrl,
    }];
  }));

  const output = `/**
 * AUTO-GENERATED by scripts/build-gen4-tcg-profiles.mjs.
 * Source: TCGdex single-card records for the exact illustration selected in
 * gen4-card-art.ts (retrieved ${new Date().toISOString().slice(0, 10)}).
 * National Dex 001-151 only. Do not hand-edit.
 */

export type Gen4CardEra = 'dp' | 'pl' | 'hgss';

export interface Gen4TcgWeakness {
  type: string;
  value?: string;
}

export interface Gen4TcgProfile {
  cardId: string;
  name: string;
  era: Gen4CardEra;
  type: string;
  weaknesses: Gen4TcgWeakness[];
  stage: string | null;
  evolvesFrom: string | null;
  sourceUrl: string;
}

export const GEN4_TCG_PROFILES_BY_ART: Record<string, Gen4TcgProfile> = ${JSON.stringify(profiles, null, 2)};
`;

  await writeFile(OUT, output);
  console.log(`Wrote ${OUT}`);
  console.log(`Profiles: ${Object.keys(profiles).length}; unique source cards: ${unique.length}`);
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
