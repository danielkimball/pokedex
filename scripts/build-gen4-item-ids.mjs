#!/usr/bin/env node

/** Build the exact Generation IV in-save item-index lookup used by PK4 data. */

import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const BASE = 'https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv';
const OUT = path.resolve('src/core/constants/items.generated.ts');

async function fetchText(filename) {
  const response = await fetch(`${BASE}/${filename}`, { headers: { 'user-agent': 'pokedex-item-id-builder/1.0' } });
  if (!response.ok) throw new Error(`${response.status} ${response.statusText}: ${filename}`);
  return response.text();
}

function parseCsvLine(line) {
  const values = [];
  let value = '';
  let quoted = false;
  for (let index = 0; index < line.length; index++) {
    const char = line[index];
    if (char === '"') {
      if (quoted && line[index + 1] === '"') { value += '"'; index++; }
      else quoted = !quoted;
    } else if (char === ',' && !quoted) {
      values.push(value);
      value = '';
    } else value += char;
  }
  values.push(value);
  return values;
}

async function main() {
  const [indicesCsv, namesCsv] = await Promise.all([
    fetchText('item_game_indices.csv'),
    fetchText('item_names.csv'),
  ]);

  const englishNames = new Map();
  for (const line of namesCsv.trim().split(/\r?\n/).slice(1)) {
    const [itemId, languageId, name] = parseCsvLine(line);
    if (Number(languageId) === 9) englishNames.set(Number(itemId), name);
  }

  const namesByGameIndex = { 0: '---' };
  for (const line of indicesCsv.trim().split(/\r?\n/).slice(1)) {
    const [itemId, generationId, gameIndex] = line.split(',').map(Number);
    if (generationId !== 4) continue;
    namesByGameIndex[gameIndex] = englishNames.get(itemId) ?? `Item #${gameIndex}`;
  }

  const sorted = Object.fromEntries(Object.entries(namesByGameIndex).sort((a, b) => Number(a[0]) - Number(b[0])));
  const source = `/**
 * AUTO-GENERATED by scripts/build-gen4-item-ids.mjs from PokeAPI's
 * Generation IV game-index table. These are PK4 held-item IDs, not the
 * API's internal item IDs. Do not hand-edit.
 */

export const GEN4_ITEM_NAMES: Record<number, string> = ${JSON.stringify(sorted, null, 2)};
`;

  await mkdir(path.dirname(OUT), { recursive: true });
  await writeFile(OUT, source);
  console.log(`Wrote ${OUT}; ${Object.keys(sorted).length - 1} Generation IV item indices.`);
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
