/**
 * Pokémon HeartGold story-order catch progression.
 * Built from LOCATIONS.heartgold + Johto/Kanto story order.
 * Badges u16: bits 0-7 Johto, 8-15 Kanto (Gen 4 trainer block).
 */

export type EncounterMethod =
  | 'wild' | 'gift' | 'static' | 'fish' | 'breed' | 'evolve' | 'trade' | 'unavailable';

export type ProgressionReq =
  | 'old-rod' | 'good-rod' | 'super-rod'
  | 'cut' | 'surf' | 'strength' | 'fly' | 'rock-smash'
  | 'whirlpool' | 'waterfall' | 'rock-climb' | 'headbutt'
  | 'national-dex';

export interface ProgressionEncounter {
  species: number;
  method: EncounterMethod;
  note?: string;
  firstHere: boolean;
  requires?: ProgressionReq[];
}

export interface ProgressionArea {
  id: string;
  name: string;
  minBadges: number;
  minKantoBadges: number;
  gymBadge: number | null;
  encounters: ProgressionEncounter[];
}

