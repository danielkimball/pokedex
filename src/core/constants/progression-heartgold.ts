export function hasBadge(badges: number, index: number): boolean {
  return ((badges >> index) & 1) === 1;
}
export function countJohtoBadges(badges: number): number {
  let n = 0; for (let i = 0; i < 8; i++) if (hasBadge(badges, i)) n++; return n;
}
export function countKantoBadges(badges: number): number {
  let n = 0; for (let i = 8; i < 16; i++) if (hasBadge(badges, i)) n++; return n;
}
export function countBadges(badges: number): number {
  return countJohtoBadges(badges) + countKantoBadges(badges);
}

