export function hgObtainableSpecies(includeTrade = false): Set<number> {
  const set = new Set<number>();
  for (const area of HG_PROGRESSION) {
    for (const e of area.encounters) {
      if (!e.firstHere) continue;
      if (e.method === 'unavailable') continue;
      if (e.method === 'trade' && !includeTrade) continue;
      set.add(e.species);
    }
  }
  return set;
}

export function hgSpeciesAvailableNow(progress: PlayerProgress, includeTrade = false): Set<number> {
  const set = new Set<number>();
  for (const area of HG_PROGRESSION) {
    if (area.id === 'event') continue;
    if (area.id === 'trade' && !includeTrade) continue;
    for (const e of area.encounters) {
      if (!e.firstHere) continue;
      if (!encounterAvailable(area, e, progress)) continue;
      if (e.method === 'trade' && !includeTrade) continue;
      set.add(e.species);
    }
  }
  return set;
}

export function hgSpeciesUpToJohtoBadges(johtoCount: number, includeTrade = false): Set<number> {
  let bits = 0;
  for (let i = 0; i < johtoCount && i < 8; i++) bits |= 1 << i;
  return hgSpeciesAvailableNow({ badges: bits, tools: inferToolsFromBadges(bits) }, includeTrade);
}
